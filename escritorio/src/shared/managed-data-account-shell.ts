export const MANAGED_DATA_ACCOUNT_POSIX_RESTORE = `DOLPHIN_DATA_ACCOUNT_DATA_HOME="\${DOLPHIN_DATA_ACCOUNT_DATA_HOME:-\${DOLPHIN_DATA_ACCOUNT_DATA_HOME:-}}"
DOLPHIN_DATA_ACCOUNT_STATE_HOME="\${DOLPHIN_DATA_ACCOUNT_STATE_HOME:-\${DOLPHIN_DATA_ACCOUNT_STATE_HOME:-}}"
DOLPHIN_DATA_ACCOUNT_PROVIDER="\${DOLPHIN_DATA_ACCOUNT_PROVIDER:-\${DOLPHIN_DATA_ACCOUNT_PROVIDER:-}}"
if [[ -n "\${DOLPHIN_DATA_ACCOUNT_DATA_HOME:-}" ]]; then
  export XDG_DATA_HOME="\${DOLPHIN_DATA_ACCOUNT_DATA_HOME}"
  export XDG_STATE_HOME="\${DOLPHIN_DATA_ACCOUNT_STATE_HOME}"
  if [[ "\${DOLPHIN_DATA_ACCOUNT_PROVIDER:-}" == opencode ]]; then
    export OPENCODE_AUTH_CONTENT=""
    export OPENCODE_DB="opencode.db"
  fi
fi`

export const MANAGED_DATA_ACCOUNT_POWERSHELL_RESTORE = `if (-not $env:DOLPHIN_DATA_ACCOUNT_DATA_HOME) { $env:DOLPHIN_DATA_ACCOUNT_DATA_HOME = $env:DOLPHIN_DATA_ACCOUNT_DATA_HOME }
if (-not $env:DOLPHIN_DATA_ACCOUNT_STATE_HOME) { $env:DOLPHIN_DATA_ACCOUNT_STATE_HOME = $env:DOLPHIN_DATA_ACCOUNT_STATE_HOME }
if (-not $env:DOLPHIN_DATA_ACCOUNT_PROVIDER) { $env:DOLPHIN_DATA_ACCOUNT_PROVIDER = $env:DOLPHIN_DATA_ACCOUNT_PROVIDER }
if ($env:DOLPHIN_DATA_ACCOUNT_DATA_HOME) {
  $env:XDG_DATA_HOME = $env:DOLPHIN_DATA_ACCOUNT_DATA_HOME
  $env:XDG_STATE_HOME = $env:DOLPHIN_DATA_ACCOUNT_STATE_HOME
  if ($env:DOLPHIN_DATA_ACCOUNT_PROVIDER -eq 'opencode') {
    $env:OPENCODE_AUTH_CONTENT = ''
    $env:OPENCODE_DB = 'opencode.db'
  }
}`

