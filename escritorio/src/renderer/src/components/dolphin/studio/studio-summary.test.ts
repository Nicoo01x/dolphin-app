import { describe, expect, it } from 'vitest'
import type { NativeChatMessage } from '../../../../../shared/native-chat/native-chat-types'
import {
  hasStudioConversation,
  mergeStudioSummaries,
  portonFailure,
  portonVerdict,
  splitStudioPath,
  summarizeStudioSession
} from './studio-summary'

const assistant = (id: string, blocks: NativeChatMessage['blocks']): NativeChatMessage => ({
  id,
  role: 'assistant',
  blocks,
  timestamp: null,
  source: 'transcript'
})

describe('the studio summary of a session', () => {
  it('counts the files it wrote (last touched first), the commands it ran and what it read', () => {
    const summary = summarizeStudioSession([
      assistant('1', [
        { type: 'tool-call', name: 'Read', input: { file_path: 'C:/repo/src/a.ts' } },
        { type: 'tool-call', name: 'Edit', input: { file_path: 'C:/repo/src/a.ts' } },
        { type: 'tool-call', name: 'Bash', input: { command: 'npm test' } }
      ]),
      assistant('2', [
        // The input can come as its JSON.
        {
          type: 'tool-call',
          name: 'Write',
          input: JSON.stringify({ file_path: 'C:/repo/README.md' })
        },
        { type: 'tool-call', name: 'Grep', input: { pattern: 'suma' } },
        { type: 'tool-call', name: 'PowerShell', input: { command: 'pnpm lint' } },
        // Editing a.ts again moves it to the front.
        {
          type: 'tool-result',
          output: 'ok',
          editPatch: { filePath: 'C:/repo/src/a.ts', hunks: [] }
        }
      ])
    ])
    expect(summary).toEqual({
      files: ['C:/repo/src/a.ts', 'C:/repo/README.md'],
      fileActions: { 'C:/repo/src/a.ts': 'editado', 'C:/repo/README.md': 'creado' },
      commands: 2,
      reads: 2
    })
  })

  it('what scrolled out of the loaded window is not forgotten, and the counts never go down', () => {
    const before = { files: ['C:/repo/viejo.ts', 'C:/repo/a.ts'], commands: 9, reads: 20 }
    const loaded = { files: ['C:/repo/nuevo.ts', 'C:/repo/a.ts'], commands: 2, reads: 3 }
    expect(mergeStudioSummaries(before, loaded)).toEqual({
      files: ['C:/repo/nuevo.ts', 'C:/repo/a.ts', 'C:/repo/viejo.ts'],
      fileActions: {},
      commands: 9,
      reads: 20
    })
  })

  it('an edit that failed or was rejected changed nothing', () => {
    const summary = summarizeStudioSession([
      assistant('1', [
        { type: 'tool-call', name: 'Edit', callId: 'a', input: { file_path: 'C:/repo/ok.ts' } },
        { type: 'tool-call', name: 'Edit', callId: 'b', input: { file_path: 'C:/repo/no.ts' } }
      ]),
      assistant('2', [
        { type: 'tool-result', callId: 'a', output: 'ok' },
        { type: 'tool-result', callId: 'b', output: 'rechazado', isError: true }
      ])
    ])
    expect(summary.files).toEqual(['C:/repo/ok.ts'])
  })

  it('a tool without a path, or with a broken input, adds nothing', () => {
    expect(
      summarizeStudioSession([
        assistant('1', [
          { type: 'tool-call', name: 'Edit', input: '{roto' },
          { type: 'tool-call', name: 'Write', input: { contenido: 'x' } },
          { type: 'text', text: 'listo' }
        ])
      ])
    ).toEqual({ files: [], fileActions: {}, commands: 0, reads: 0 })
  })

  it('a session cleared with /clear has messages but nothing to show', () => {
    const user = (text: string): NativeChatMessage => ({
      id: text,
      role: 'user',
      blocks: [{ type: 'text', text }],
      timestamp: null,
      source: 'transcript'
    })
    expect(
      hasStudioConversation([
        user('<local-command-caveat>Caveat: The messages below were generated by the user…'),
        user('<command-name>/clear</command-name>'),
        user('   ')
      ])
    ).toBe(false)
    expect(hasStudioConversation([user('arreglá el carrito')])).toBe(true)
    expect(
      hasStudioConversation([assistant('1', [{ type: 'tool-call', name: 'Read', input: {} }])])
    ).toBe(true)
  })

  it('shows a path as its name and its folder, with either slash', () => {
    expect(splitStudioPath('C:\\repo\\src\\carrito.ts')).toEqual({
      name: 'carrito.ts',
      folder: 'C:/repo/src'
    })
    expect(splitStudioPath('README.md')).toEqual({ name: 'README.md', folder: '' })
  })
})

describe('the studio porton', () => {
  const run = (estados: ('paso' | 'fallo' | 'esperando' | 'salteada')[]) => ({
    desde: 'antes',
    hasta: 'después',
    fases: estados.map((estado, i) => ({
      nombre: `fase-${i}`,
      estado,
      ...(estado === 'fallo' ? { detalle: `fase-${i}: ✖ suma` } : {})
    }))
  })

  it('reads a run in one word: what the color paints', () => {
    expect(portonVerdict(null, false)).toBe('idle')
    expect(portonVerdict(run([]), false)).toBe('idle')
    expect(portonVerdict(run(['paso']), true)).toBe('running')
    expect(portonVerdict(run(['salteada', 'paso']), false)).toBe('passed')
    expect(portonVerdict(run(['paso', 'fallo', 'esperando']), false)).toBe('failed')
  })

  it('«passed» has to be earned: nothing ran is not a pass, and a run cut halfway is not one either', () => {
    expect(portonVerdict(run(['salteada', 'salteada']), false)).toBe('skipped')
    const cut = {
      desde: 'antes',
      fases: [
        { nombre: 'typecheck', estado: 'paso' as const },
        { nombre: 'test', estado: 'corriendo' as const }
      ]
    }
    expect(portonVerdict(cut, false)).toBe('interrupted')
    expect(portonVerdict(run(['paso']), false, true)).toBe('interrupted')
    expect(portonVerdict(null, false, true)).toBe('interrupted')
  })

  it('names the phase that stopped the run, with its reason', () => {
    expect(portonFailure(run(['paso', 'fallo', 'esperando']))).toMatchObject({
      nombre: 'fase-1',
      detalle: 'fase-1: ✖ suma'
    })
    expect(portonFailure(run(['paso']))).toBeNull()
  })
})
